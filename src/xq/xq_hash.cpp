const u64 ZobristPlayer = 0xA0CE2AF90C452F58ULL;

/// Row of the Zobrist table for a piece: our own types, king..pawn as 0..6,
/// plus 7 for Black, and the two covered-piece rows on the end.
///
/// The side is part of the row, so a white rook and a black rook on the same
/// point hash differently: a book's positions from thousands of games share
/// one key space.
static inline int zobristRow(const Piece& piece)
{
    const int sd = 1 - static_cast<int>(piece.side);
    assert(sd == 0 || sd == 1);
    if (piece.type == COVERXQ) {
        return 14 + sd;
    }
    const int row = (piece.type - 1) + 7 * sd;
    assert(row >= 0 && row < 14);
    return row;
}

u64 XqBoard::xorHashKey(int pos) const
{
    assert(isPositionValid(pos));
    assert(pos >= 0 && pos < 90);

    auto piece = pieces[pos];
    assert(!piece.isEmpty());

    return ZobristTableXq[zobristRow(piece)][pos];
}

u64 XqBoard::xorSideHashKey() const
{
    return ZobristPlayer;
}


u64 XqBoard::initHashKey() const
{
    u64 key = 0;
    for (auto i = 0; static_cast<size_t>(i) < pieces.size(); i++) {
        if (!pieces[i].isEmpty()) {
            key ^= xorHashKey(i);
        }
    }

    if (side == Side::white) {
        key ^= xorSideHashKey();
    }
    return key;
}

