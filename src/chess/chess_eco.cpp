extern const std::vector<Eco> ecoVec;

static auto& ecoMap() // built on first use, not at load time (clazy non-pod-global-static, 2026-11-15)
{
    static std::map<u64, int> v;
    return v;
}
static auto& ecoNameSet() // built on first use, not at load time (clazy non-pod-global-static, 2026-11-15)
{
    static std::set<std::string> v;
    return v;
}

/// The tables are built on first use, which can come from several threads at once (an
/// opening tree reads games on a pool): once, under call_once
static std::once_flag ecoInitFlag;
static void ecoInit()
{
    std::call_once(ecoInitFlag, [] {
        for (size_t i = 0; i < ecoVec.size(); ++i) {
            auto e = ecoVec[i];
            ecoMap()[e.hash] = i;
            ecoNameSet().insert(e.ecoString);
        }
    });
}

Eco ChessBoard::getEco(u64 key) const
{
    ecoInit();

    auto it = ecoMap().find(key);
    if (it != ecoMap().end()) {
        auto r = it->second;
        if (static_cast<size_t>(r) < ecoVec.size()) return ecoVec.at(r);
    }
    return Eco();
}

bool ChessBoard::isEcoName(const std::string name) const
{
    ecoInit();
    return ecoNameSet().find(name) != ecoNameSet().end();
}


